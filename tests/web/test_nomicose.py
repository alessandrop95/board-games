# gioco: nomicose
"""Nomi, cose, città nel browser con tre telefoni: Ale (host) e Cri nella stessa squadra, Bea nell'altra.
Squadre in sala d'attesa, foglio comune che si aggiorna in diretta per i compagni (e resta nascosto agli altri),
stop, controllo con contestazione e voto, punti della manche e fine della partita. Serve: broker su 8897 (vedi tests/run.sh)."""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'lib'))
from check import t, done
from playwright.sync_api import sync_playwright
U = 'http://localhost:8897/nomicose/?broker=ws://localhost:8897/'
OUT = os.environ.get('OUT', '/tmp')
errs = []
with sync_playwright() as p:
    br = p.chromium.launch()
    def phone(nick):
        c = br.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
        c.add_init_script("try{localStorage.setItem('pp-nick',%s);localStorage.setItem('nc-intro-done','1')}catch(e){}" % json.dumps(nick))
        pg = c.new_page(); pg.on('pageerror', lambda e: errs.append(nick + ': ' + str(e)))
        return pg
    def js(P, s): return P.evaluate(s)
    def click(P, sel): P.evaluate("(function(){var e=document.querySelector(%s); if(!e) throw new Error('manca '+%s); e.dispatchEvent(new MouseEvent('click',{bubbles:true}));})()" % (json.dumps(sel), json.dumps(sel)))
    def host(P, code): js(P, "Net.hostApply(function(cur){var g=cur.game;%s;g.seq++;return true})" % code)
    def typ(P, cat, word): P.evaluate("(function(){var i=document.querySelector('#in-%s'); i.focus(); i.value=%s; i.dispatchEvent(new Event('input',{bubbles:true})); i.blur();})()" % (cat, json.dumps(word)))

    A = phone('Ale'); A.goto(U); A.wait_for_timeout(800)
    t('nella home del gioco il nome e le regole in breve', 'Nomi, cose, città' in A.inner_text('h1') and 'lettera' in A.inner_text('.lobby'))
    A.click('[data-act=create]'); A.wait_for_function('App.doc && App.doc.code', timeout=15000); code = js(A, 'App.code')
    B = phone('Bea'); B.goto(U + '&t=' + code); B.wait_for_function('App.doc && App.doc.seats.length === 2', timeout=15000)
    C = phone('Cri'); C.goto(U + '&t=' + code); C.wait_for_function('App.doc && App.doc.seats.length === 3', timeout=15000)
    A.wait_for_function('App.doc.seats.length === 3', timeout=10000)
    teams = js(A, 'App.doc.seats.map(function(s){return s.team})')
    t('chi arriva va nella squadra con meno giocatori', teams == [0, 1, 0], teams)
    t('le squadre si vedono in sala d’attesa', A.locator('.tbox').count() == 2 and 'Bea' in A.inner_text('.tbox:nth-child(2)'))
    click(B, '[data-act=team][data-uid="%s"]' % js(B, 'Net.uid')); A.wait_for_function('App.doc.seats[1].team === 0', timeout=10000)
    click(A, '[data-act=start]'); A.wait_for_timeout(800)
    t('con una squadra sola non si comincia', js(A, 'App.doc.phase') == 'lobby')
    click(B, '[data-act=team][data-uid="%s"]' % js(B, 'Net.uid')); A.wait_for_function('App.doc.seats[1].team === 1', timeout=10000)
    A.select_option('#opt-time', '60'); B.wait_for_function('App.doc.opts.time === 60', timeout=10000)
    t('Bea vede le opzioni', '60 secondi' in B.inner_text('.lobby') and '2 squadre' in B.inner_text('.lobby'))
    click(A, '[data-act=start]')
    for P in (A, B, C): P.wait_for_selector('#gv', timeout=15000)
    g = js(A, 'G()')
    t('una lettera, 6 categorie e due squadre', len(g['cats']) == 6 and len(g['teams']) == 2 and g['phase'] == 'write')
    host(A, "g.letter='M'"); A.wait_for_function("G().letter === 'M'", timeout=10000)
    for P in (A, B, C): P.wait_for_selector('#in-nome', timeout=10000)
    t('ognuno vede il foglio con 6 caselle', all(P.locator('.cin').count() == 6 for P in (A, B, C)))
    typ(A, 'nome', 'Marco')
    C.wait_for_function("document.querySelector('#in-nome').value === 'Marco'", timeout=10000)
    t('il compagno vede subito la parola, con chi l’ha scritta', C.locator('#by-nome .pv').count() == 1)
    t('l’altra squadra no', js(B, "document.querySelector('#in-nome').value") == '')
    typ(C, 'cosa', 'Martello'); typ(C, 'citta', 'Milano'); typ(A, 'animale', 'Mucca'); typ(A, 'frutta', 'Mela'); typ(A, 'mestiere', 'Medico')
    typ(B, 'nome', 'Marco'); typ(B, 'citta', 'Bari'); typ(B, 'animale', 'Merlo')
    A.wait_for_function("G().ans[G().players[myIdx()].team].mestiere && G().ans[G().players[myIdx()].team].cosa", timeout=10000)
    A.wait_for_selector('[data-act=stop]', timeout=10000)
    t('foglio pieno: c’è il pulsante Stop', A.locator('[data-act=stop]').count() == 1 and B.locator('[data-act=stop]').count() == 0)
    A.screenshot(path=os.path.join(OUT, 'nomicose-foglio.png'))
    click(A, '[data-act=stop]'); B.wait_for_function('G().stop', timeout=10000)
    t('stop: agli altri restano 10 secondi', js(B, 'G().until - G().clock') <= 10500 and 'STOP' in B.inner_text('#gv-prompt'))
    host(A, "g.until=Date.now()")
    for P in (A, B, C): P.wait_for_function("G().phase === 'review'", timeout=15000)
    t('dopo il tempo si vedono le risposte di tutti', 'Merlo' in A.inner_text('#gv-main') and 'Martello' in B.inner_text('#gv-main'))
    t('la lettera sbagliata vale 0', 'non è M' in A.inner_text('#gv-main'))
    t('le parole uguali valgono 5', js(A, "E.points(G()).pts[0].nome") == 5 and js(A, "E.points(G()).pts[1].nome") == 5)
    a = js(A, 'myIdx()'); ta = js(A, 'G().players[myIdx()].team')
    t('non si contesta la propria squadra', A.locator('[data-act=flag][data-t="%d"]' % ta).count() == 0)
    click(B, '[data-act=flag][data-t="%d"][data-c="animale"]' % ta); A.wait_for_function("G().flags['%d:animale']" % ta, timeout=10000)
    t('la squadra contestata non vota', A.locator('[data-act=vote]').count() == 0)
    B.screenshot(path=os.path.join(OUT, 'nomicose-controllo.png'))
    for P in (A, B, C): P.wait_for_selector('[data-act=ready]', timeout=10000); click(P, '[data-act=ready]')
    A.wait_for_function("G().phase === 'scores'", timeout=15000)
    t('contestata con più no che sì: vale 0', js(A, 'G().res.pts[%d].animale' % ta) == 0)
    A.wait_for_selector('.sh-round', timeout=10000)
    t('i punti della manche', 'Punti della manche' in A.inner_text('.sh-round') and js(A, 'G().teams[%d].total' % ta) == js(A, 'G().res.tot[%d]' % ta))
    host(A, "g.opts.rounds=2")
    for P in (A, B, C): click(P, '.sh-round [data-act=next]')
    A.wait_for_function("G().round === 2 && G().phase === 'write'", timeout=10000)
    t('nuova manche con un’altra lettera e il foglio vuoto', js(A, "G().letter") != 'M' and js(A, "document.querySelector('#in-nome').value") == '')
    host(A, "g.until=Date.now()")
    for P in (A, B, C): P.wait_for_function("G().phase === 'review' && document.querySelector('[data-act=ready]')", timeout=15000)
    for P in (A, B, C): click(P, '[data-act=ready]')
    for P in (A, B, C): P.wait_for_selector('.sh-over', timeout=15000)
    t('fine della partita con la classifica delle squadre', 'Avete vinto' in A.inner_text('.sh-over') or 'Vincono' in A.inner_text('.sh-over') or 'Pari' in A.inner_text('.sh-over'))
    A.screenshot(path=os.path.join(OUT, 'nomicose-fine.png'))
    t('nessun errore nelle pagine', not errs, errs)
    br.close()
done()
