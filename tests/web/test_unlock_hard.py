"""Unlock! nel browser, avventure difficili: livelli su 4, «Cerca» per i numeri da calcolare, indizi contati (2 al livello 3,
1 al livello 4) con i pulsanti che si bloccano, macchina a sequenza, tempo scaduto = avventura persa e «Ricomincia da capo».
Serve: broker su 8897 (vedi tests/run.sh)."""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'lib'))
from check import t, done
from playwright.sync_api import sync_playwright
U = 'http://localhost:8897/unlock/?broker=ws://localhost:8897/'
OUT = os.environ.get('OUT', '/tmp')
errs = []
with sync_playwright() as p:
    br = p.chromium.launch()
    def phone(nick):
        c = br.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
        c.add_init_script("try{localStorage.setItem('pp-nick',%s);localStorage.setItem('ul-intro-done','1')}catch(e){}" % json.dumps(nick))
        pg = c.new_page(); pg.on('pageerror', lambda e: errs.append(nick + ': ' + str(e)))
        return pg
    def js(P, s): return P.evaluate(s)
    def click(P, sel): P.evaluate("(function(){var e=document.querySelector(%s); if(!e) throw new Error('manca '+%s); e.dispatchEvent(new MouseEvent('click',{bubbles:true}));})()" % (json.dumps(sel), json.dumps(sel)))
    def idle(P): P.wait_for_function('Game.idle() && !document.querySelector(".ov")', timeout=30000); P.wait_for_timeout(250)
    def act(P, a): js(P, "Net.send({t:'act',a:%s})" % json.dumps(a)); P.wait_for_timeout(250)

    A = phone('Ale'); A.goto(U); A.wait_for_timeout(1000)
    t('sei avventure, difficoltà su 4', A.locator('.scn').count() == 6 and '4/4' in A.inner_text('.scns') and 'estremo' in A.inner_text('.scns').lower())
    A.click('[data-act=create]'); A.wait_for_function('App.doc && App.doc.code', timeout=15000); code = js(A, 'App.code')
    B = phone('Bea'); B.goto(U + '&t=' + code); B.wait_for_function('App.doc && App.doc.seats.length === 2', timeout=15000)
    click(A, '[data-act=scen][data-s=treno]'); B.wait_for_function("App.doc.opts.scen === 'treno'", timeout=10000)
    click(A, '[data-act=start]')
    for P in (A, B): P.wait_for_selector('#gv', timeout=15000)
    t('Espresso di Mezzanotte: livello 3, 60 minuti', js(A, 'G().limit') == 3600 and js(A, "UScen.get(G().scen).level") == 3)
    t('pulsante Cerca e indizi 2/2', B.locator('[data-act=search]').count() == 1 and '2/2' in B.inner_text('.hud'))
    for s in ['A', '21', '3']: act(A, {'a': 'reveal', 'id': s})
    idle(A); idle(B); js(B, 'Game.closeView()')
    # Bea cerca la cabina senza il biglietto: non si trova e costa tempo
    click(B, '[data-act=search]'); B.wait_for_selector('.kp.srch')
    for k in '68': click(B, '[data-act=kp][data-k="%s"]' % k)
    click(B, '[data-act=srok]'); B.wait_for_selector('.kp.srch.err', timeout=10000)
    t('cerca senza indizi: NIENTE e −2 minuti', js(B, 'G().pen') == 120 and 'NIENTE' in B.inner_text('.kp-lcd') and not js(B, "E.seen(G(), '68')"))
    click(B, '[data-act=close]')
    act(A, {'a': 'reveal', 'id': '5'}); idle(B); js(B, 'Game.closeView()')
    click(B, '[data-act=search]')
    for k in '68': click(B, '[data-act=kp][data-k="%s"]' % k)
    click(B, '[data-act=srok]')
    A.wait_for_function("E.onTable(G(), '68')", timeout=10000)
    t('con il biglietto la cabina 68 si trova', js(A, "G().st['68']") == 'table' and js(A, 'G().pen') == 120)
    idle(A); idle(B)
    # indizi: due in tutto, poi i pulsanti si bloccano
    js(A, "Game.openView('68')"); A.wait_for_selector('#vw-panel [data-act=hintask]')
    click(A, '#vw-panel [data-act=hintask]'); t('il pulsante dice quanto costa', '1 min' in A.inner_text('#vw-panel [data-act=hint]')); click(A, '#vw-panel [data-act=hint]')
    A.wait_for_function('G().hintN === 1', timeout=10000); A.wait_for_timeout(300)
    t('indizio: −1 minuto, ne resta uno', js(A, 'G().pen') == 180 and js(A, 'E.hintsLeft(G())') == 1)
    click(A, '#vw-panel [data-act=hintask]'); click(A, '#vw-panel [data-act=hint]'); A.wait_for_function('G().hintN === 2', timeout=10000)
    B.wait_for_function('G().hintN === 2', timeout=10000); js(B, "Game.openView('5')"); B.wait_for_timeout(400)
    t('indizi finiti: niente più pulsanti per nessuno', B.locator('#vw-panel [data-act=hintask]').count() == 0 and 'Indizi finiti' in B.inner_text('#vw-panel') and '0/2' in B.inner_text('.hud'))
    r = js(B, "Net.send({t:'act',a:{a:'hint',id:'5',lvl:1}}).then(function(){return 'ok'},function(e){return String(e)})")
    t('anche forzando, il server rifiuta un altro indizio', 'finito' in r, r)
    js(B, 'Game.closeView()')
    # macchina a sequenza (il banco di guida) con la leva riparata
    js(A, "Net.hostApply(function(cur){var g=cur.game;['B','41','56','C','D','38','22','60','70','54','39'].forEach(function(id){if(!g.st[id]){g.st[id]='table';g.order.push(id);}});return true})"); A.wait_for_function("E.onTable(G(),'70')", timeout=10000)
    idle(B); js(B, "Game.openView('70')"); B.wait_for_selector('#vw-panel [data-act=mac]'); click(B, '#vw-panel [data-act=mac]')
    for lab in ['PFEIFE', 'SANDER', 'REGLER', 'BREMSE']: B.evaluate("[].slice.call(document.querySelectorAll('[data-act=sq]')).filter(function(b){return b.textContent.indexOf(%s)>=0})[0].click()" % json.dumps(lab))
    t('la sequenza si vede passo per passo', B.locator('.sq-st').count() == 4)
    pen0 = js(B, 'G().pen'); click(B, '[data-act=mgo]'); B.wait_for_function('G().pen > %d' % pen0, timeout=10000)
    t('ordine sbagliato: −2 minuti', js(B, 'G().pen') == pen0 + 120)
    click(B, '[data-act=sqdel]')
    for lab in ['PFEIFE', 'REGLER', 'SANDER', 'BREMSE']: B.evaluate("[].slice.call(document.querySelectorAll('[data-act=sq]')).filter(function(b){return b.textContent.indexOf(%s)>=0})[0].click()" % json.dumps(lab))
    B.screenshot(path=os.path.join(OUT, 'unlock-sequenza.png'))
    click(B, '[data-act=mgo]'); A.wait_for_function("G().phase === 'over'", timeout=15000)
    t('fischio, regolatore, sabbiera, freno: il treno si ferma', js(A, 'G().won') is True and not js(A, 'G().lost'))
    A.wait_for_selector('.sh-over', timeout=20000); click(A, '.sh-over [data-act=rematch]'); A.wait_for_function("App.doc.phase === 'lobby'", timeout=10000)
    # tomba: un solo indizio; il tempo scade e si ricomincia da capo
    click(A, '[data-act=scen][data-s=tomba]'); A.wait_for_function("App.doc.opts.scen === 'tomba'", timeout=10000); click(A, '[data-act=start]')
    for P in (A, B): P.wait_for_function("G() && G().scen === 'tomba' && G().phase === 'play'", timeout=15000)
    t('la tomba: livello 4, un solo indizio', js(B, "UScen.get(G().scen).level") == 4 and '1/1' in B.inner_text('.hud'))
    act(A, {'a': 'reveal', 'id': 'A'}); act(A, {'a': 'reveal', 'id': '3'}); act(A, {'a': 'reveal', 'id': '18'})
    act(A, {'a': 'combine', 'r': '18', 'b': '3'})
    A.wait_for_function("G().st['21'] === 'gone'", timeout=10000)
    t('trappola degli scorpioni: −3 minuti', js(A, 'G().pen') == 180)
    js(A, "Net.hostApply(function(cur){var g=cur.game; g.el = g.limit*1000 - g.pen*1000 - 2500; g.at = Date.now(); return true})")
    for P in (A, B): P.wait_for_function("G().phase === 'over'", timeout=15000)
    t('allo zero l’avventura è persa per tutti', js(B, 'G().lost') is True and js(B, 'G().won') is False and js(B, 'App.doc.phase') == 'over')
    B.wait_for_selector('.ov-time', timeout=10000); t('Bea vede «Tempo scaduto!»', 'Tempo scaduto' in B.inner_text('.ov-time'))
    B.screenshot(path=os.path.join(OUT, 'unlock-tempo-scaduto.png'))
    for P in (A, B): P.wait_for_selector('.sh-over', timeout=20000)
    t('solo l’host può ricominciare', A.locator('.sh-over [data-act=restart]').count() == 1 and B.locator('.sh-over [data-act=restart]').count() == 0)
    t('nessuna azione dopo lo zero', 'finita' in js(B, "Net.send({t:'act',a:{a:'reveal',id:'14'}}).then(function(){return 'ok'},function(e){return String(e)})"))
    click(A, '.sh-over [data-act=restart]')
    for P in (A, B): P.wait_for_function("G().phase === 'play' && E.table(G()).join() === 'start'", timeout=15000)
    t('di nuovo da capo: tutte le carte coperte, tempo e penalità azzerati', js(B, 'G().pen') == 0 and js(B, 'G().hintN') == 0 and js(B, 'E.remaining(G(), Clock.now())') > 3590000 and js(B, 'App.sheet') is None)
    br.close()
t('nessun errore nelle pagine', not errs, errs[:4])
done()
