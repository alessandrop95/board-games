"""Skyjo nel browser con due telefoni (Ale host e Bea) e un giocatore automatico: prime due carte, pesca dal mazzo,
scarto e carta scoperta, presa dagli scarti, colonna di tre carte uguali che sparisce, fine della manche con il raddoppio,
«Prossima manche» e fine della partita con la classifica. Serve: broker su 8897 (vedi tests/run.sh)."""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'lib'))
from check import t, done
from playwright.sync_api import sync_playwright
U = 'http://localhost:8897/skyjo/?broker=ws://localhost:8897/'
OUT = os.environ.get('OUT', '/tmp')
errs = []
with sync_playwright() as p:
    br = p.chromium.launch()
    def phone(nick):
        c = br.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
        c.add_init_script("try{localStorage.setItem('pp-nick',%s);localStorage.setItem('sk-intro-done','1')}catch(e){}" % json.dumps(nick))
        pg = c.new_page(); pg.on('pageerror', lambda e: errs.append(nick + ': ' + str(e)))
        return pg
    def js(P, s): return P.evaluate(s)
    def click(P, sel): P.evaluate("(function(){var e=document.querySelector(%s); if(!e) throw new Error('manca '+%s); e.dispatchEvent(new MouseEvent('click',{bubbles:true}));})()" % (json.dumps(sel), json.dumps(sel)))
    def idle(P): P.wait_for_function('Game.idle() && !document.querySelector(".flyer")', timeout=20000); P.wait_for_timeout(200)
    def host(P, code): js(P, "Net.hostApply(function(cur){var g=cur.game;%s;g.seq++;return true})" % code)

    A = phone('Ale'); A.goto(U); A.wait_for_timeout(1000)
    t('home del gioco', 'Skyjo' in A.inner_text('h1') and A.locator('.hero-art .skc').count() >= 5)
    A.click('[data-act=create]'); A.wait_for_function('App.doc && App.doc.code', timeout=15000); code = js(A, 'App.code')
    B = phone('Bea'); B.goto(U + '&t=' + code); B.wait_for_function('App.doc && App.doc.seats.length === 2', timeout=15000)
    A.wait_for_function('App.doc.seats.length === 2', timeout=10000)
    click(A, '[data-act=addbot]'); A.wait_for_function('App.doc.seats.length === 3', timeout=10000)
    A.select_option('#opt-target', '50'); B.wait_for_function('App.doc.opts.target === 50', timeout=10000)
    t('Bea vede la soglia scelta dall’host', '50 punti' in B.inner_text('.lobby'))
    click(A, '[data-act=start]')
    for P in (A, B): P.wait_for_selector('#gv', timeout=15000)
    g = js(A, 'G()')
    t('12 carte coperte a testa e una sugli scarti', all(len(P['grid']) == 12 for P in g['players']) and len(g['disc']) == 1 and len(g['deck']) == 150 - 36 - 1)
    idle(A)
    t('due griglie degli altri in alto, la mia grande in basso', A.locator('.opp').count() == 2 and A.locator('.board.big .slot').count() == 12)
    t('si devono scoprire due carte', 'Scopri 2 carte' in A.inner_text('#gv-prompt') and A.locator('.board.big .slot.can').count() == 12)
    click(A, '.board.big .slot[data-i="0"]'); A.wait_for_function('E.flips(G().players[myIdx()]) === 1', timeout=10000)
    click(A, '.board.big .slot[data-i="5"]'); A.wait_for_function('E.flips(G().players[myIdx()]) === 2', timeout=10000)
    t('dopo due carte non se ne scoprono altre', A.locator('.board.big .slot.can').count() == 0)
    a = js(A, 'myIdx()'); b = js(B, 'myIdx()')
    B.wait_for_function('G().players[%d].grid[0].up' % a, timeout=10000)
    t('Bea vede le carte scoperte di Ale', js(B, "document.querySelectorAll('.board[data-p=\"%d\"] .skc.up').length" % a) == 2)
    for i in (2, 9): click(B, '.board.big .slot[data-i="%d"]' % i); B.wait_for_timeout(300)
    A.wait_for_function("G().phase === 'play'", timeout=15000)
    t('tutti pronti: si gioca', js(A, 'G().phase') == 'play')
    # tocca ad Ale, con mazzo e scarti preparati
    host(A, "g.turn=%d;g.drawn=null;g.turnN++;g.deck.push(-2);g.disc.push(11)" % a); A.wait_for_function('G().turn === myIdx() && !G().drawn', timeout=10000); idle(A)
    t('il mio turno: mazzo e scarti si accendono', A.locator('.pile.deck.can').count() == 1 and A.locator('.pile.disc.can').count() == 1)
    t('Bea non può pescare', (click(B, '[data-act=deck]') or True) and B.wait_for_timeout(300) is None and not js(B, 'G().drawn'))
    click(A, '[data-act=deck]'); A.wait_for_function('G().drawn && G().drawn.v === -2', timeout=10000)
    B.wait_for_function('G().drawn', timeout=10000); B.wait_for_timeout(700)
    idle(B); t('tutti vedono la carta pescata', B.locator('#hand .hc-card').count() == 1 and 'ale' in B.inner_text('#hand .pl').lower(), B.inner_text('#hand .pl'))
    idle(A); A.screenshot(path=os.path.join(OUT, 'skyjo-pescata.png'))
    old = js(A, 'G().players[myIdx()].grid[3].v')
    click(A, '.board.big .slot[data-i="3"]')
    A.wait_for_function('G().players[%d].grid[3].v === -2 && G().players[%d].grid[3].up' % (a, a), timeout=10000)
    t('tengo il −2 al posto di una carta coperta, che va sugli scarti', js(A, 'G().disc[G().disc.length-1]') == old and js(A, 'G().turn') != a)
    # scarta e scopri
    host(A, "g.turn=%d;g.drawn=null;g.turnN++;g.deck.push(12)" % a); A.wait_for_function('G().turn === myIdx() && !G().drawn', timeout=10000); idle(A)
    click(A, '[data-act=deck]'); A.wait_for_function('G().drawn && G().drawn.v === 12', timeout=10000); idle(A)
    click(A, '[data-act=disc]')
    t('scartando si accendono solo le carte coperte', js(A, 'App.mode') == 'drop' and A.locator('.board.big .slot.can').count() == js(A, 'E.hidden(G().players[myIdx()]).length'))
    click(A, '.board.big .slot[data-i="0"]'); A.wait_for_timeout(300)
    t('una carta già scoperta non si può scegliere', js(A, 'G().drawn') is not None)
    click(A, '.board.big .slot[data-i="7"]'); A.wait_for_function('G().players[%d].grid[7].up' % a, timeout=10000)
    t('12 sugli scarti e carta scoperta', js(A, 'G().disc[G().disc.length-1]') == 12)
    # colonna di tre carte uguali
    host(A, "var P=g.players[%d];P.grid[1]={v:6,up:true};P.grid[5]={v:6,up:true};P.grid[9]={v:4,up:false};g.turn=%d;g.drawn=null;g.turnN++;g.disc.push(6)" % (a, a))
    A.wait_for_function('G().turn === myIdx() && G().disc[G().disc.length-1] === 6', timeout=10000); idle(A)
    click(A, '[data-act=disc]'); t('gli scarti si sollevano', A.locator('.pile.disc.picked').count() == 1)
    click(A, '.board.big .slot[data-i="9"]')
    A.wait_for_selector('.flyer.still', timeout=5000)
    t('la colonna brilla prima di volare via', A.locator('.flyer.still').count() == 3)
    A.screenshot(path=os.path.join(OUT, 'skyjo-colonna.png'))
    A.wait_for_function('G().players[%d].grid[1] === null && G().players[%d].grid[9] === null' % (a, a), timeout=10000); idle(A)
    t('la colonna di 6 è sparita', A.locator('.board.big .slot.gone').count() == 3 and js(A, 'G().disc.slice(-3).join()') == '6,6,6')
    # fine manche: Ale chiude con più punti di Bea e raddoppia
    host(A, "var P=g.players[%d],V=[5,0,6,7,8,0,9,10,11,0,12,4];for(var i=0;i<12;i++){if(P.grid[i]){P.grid[i]={v:V[i],up:i!==11};}}P.grid[1]=P.grid[5]=P.grid[9]=null;g.players.forEach(function(Q,k){if(k!==%d){for(var j=0;j<12;j++)Q.grid[j]={v:0,up:j<10};}});g.turn=%d;g.drawn=null;g.turnN++;g.deck.push(3);g.opts.target=150" % (a, a, a))
    A.wait_for_function('G().turn === myIdx() && !G().drawn', timeout=10000); idle(A)
    click(A, '[data-act=deck]'); A.wait_for_function('G().drawn', timeout=10000); idle(A)
    click(A, '[data-act=disc]'); click(A, '.board.big .slot[data-i="11"]')
    A.wait_for_function('G().ender === myIdx()', timeout=10000)
    t('chi scopre tutto chiude: ultimo giro', js(A, 'G().ender') == a)
    B.wait_for_selector('.lastbar', timeout=10000); t('Bea vede «Ultimo giro»', 'Ultimo giro' in B.inner_text('.lastbar'))
    B.wait_for_function('G().turn === myIdx()', timeout=20000); idle(B)
    t('ultimo turno anche per Bea', 'ultimo turno' in B.inner_text('#gv-prompt'))
    click(B, '[data-act=deck]'); B.wait_for_function('G().drawn', timeout=10000); idle(B); click(B, '[data-act=disc]'); click(B, '.board.big .slot[data-i="10"]')
    A.wait_for_function("G().phase === 'scores'", timeout=30000)
    A.wait_for_selector('.sh-round', timeout=20000); B.wait_for_selector('.sh-round', timeout=20000)
    rr = js(A, 'G().roundRes')
    t('Ale chiude con 72 senza essere il più basso: 144 punti', rr['raw'][a] == 72 and rr['pts'][a] == 144 and rr['doubled'], rr)
    t('il raddoppio si vede', A.locator('.sh-round .stamp').count() == 1 and 'raddoppiano' in A.inner_text('.sh-round'))
    A.screenshot(path=os.path.join(OUT, 'skyjo-manche.png'))
    click(A, '.sh-round [data-act=next]'); A.wait_for_function('G().players[myIdx()].ready', timeout=10000)
    t('Ale pronto, si aspetta Bea', js(A, "G().phase") == 'scores' and 'Bea' in A.inner_text('.sh-round'))
    click(B, '.sh-round [data-act=next]')
    for P in (A, B): P.wait_for_function("G().phase === 'reveal' && G().round === 2", timeout=10000)
    t('nuova manche: carte nuove e il cielo cambia', js(A, "document.getElementById('gv').getAttribute('data-sky')") == '2' and js(A, 'App.sheet') is None)
    # fine partita
    host(A, "g.players.forEach(function(Q,k){Q.total=k===%d?10:145;Q.hist=[Q.total];});g.phase='reveal'" % b)
    idle(A); host(A, "g.players.forEach(function(Q){Q.grid.forEach(function(x,i){x.up=i<2;});});g.phase='play';g.turn=%d;g.drawn=null;g.ender=null" % a)
    host(A, "var P=g.players[%d];P.grid.forEach(function(x,i){x.up=i!==11;});g.deck.push(1)" % a); A.wait_for_function('G().turn === myIdx() && G().phase === "play"', timeout=10000); idle(A)
    click(A, '[data-act=deck]'); A.wait_for_function('G().drawn', timeout=10000); idle(A); click(A, '[data-act=disc]'); click(A, '.board.big .slot[data-i="11"]')
    B.wait_for_function('G().turn === myIdx() && !G().drawn', timeout=20000); idle(B)
    hb = js(B, 'E.hidden(G().players[myIdx()])[0]')
    click(B, '[data-act=deck]'); B.wait_for_function('G().drawn', timeout=10000); idle(B); click(B, '[data-act=disc]'); click(B, '.board.big .slot[data-i="%d"]' % hb)
    for P in (A, B): P.wait_for_function("G().phase === 'over'", timeout=40000)
    for P in (A, B): P.wait_for_selector('.sh-over', timeout=20000)
    t('vince Bea con il totale più basso', js(B, 'G().winners') == [b] and 'Hai vinto' in B.inner_text('.sh-over'))
    t('podio e segnapunti', B.locator('.podium .pod').count() == 3 and B.locator('.scard tr').count() >= 3)
    B.screenshot(path=os.path.join(OUT, 'skyjo-fine.png'))
    t('l’host può rigiocare', A.locator('.sh-over [data-act=rematch]').count() == 1)
    br.close()
t('nessun errore nelle pagine', not errs, errs[:4])
done()
